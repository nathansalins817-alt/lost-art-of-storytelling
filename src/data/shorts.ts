export function getShortBySlug(slug: string) {
  return shorts.find((short) => short.slug === slug);
}

export function getTrendingShorts(count?: number) {
  const trending = shorts.filter((short) => short.trending);
  return count ? trending.slice(0, count) : trending;
}

export function getLatestShorts(count?: number) {
  const sorted = [...shorts].sort(
    (a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
  );
  return count ? sorted.slice(0, count) : sorted;
}
